/** 그 날의 공휴일 이름(대체공휴일이면 원래 휴일 이름). 없으면 null. */
export function holidayName(dayKey: string): string | null {
  return koreanHolidays[dayKey]?.[0] ?? null
}

/** 화면에 적을 말. 대체공휴일은 **'대체공휴일'**이라고만 적는다.
 *
 *  '광복절 대체'처럼 이름을 붙이면 원래 날(8/15)에도 '광복절'이 있어 같은 이름이 두 번
 *  나오고, 어느 쪽이 진짜인지 오히려 헷갈린다. */
export function holidayLabel(dayKey: string): string | null {
  const h = koreanHolidays[dayKey]
  if (!h) return null
  return h[1] ? '대체공휴일' : h[0]
}

/** 대체공휴일인가. */
export function isSubstituteHoliday(dayKey: string): boolean {
  return koreanHolidays[dayKey]?.[1] ?? false
}

/** 쉬는 날인가 — 주말이거나 공휴일. 달력에서 숫자를 빨갛게 칠할 기준.
 *
 *  토요일도 포함한다: 법정공휴일은 아니지만 달력에서 토요일을 검게 두면
 *  "이번 주말 언제였지"를 매번 세어야 한다. */
export function isRestDay(dayKey: string): boolean {
  if (dayKey in koreanHolidays) return true
  const w = weekdayOf(dayKey)
  return w === 0 || w === 6
}

/** 일요일·공휴일인가 — 토요일과 **다른 색**을 주고 싶을 때. */
export function isSundayOrHoliday(dayKey: string): boolean {
  return dayKey in koreanHolidays || weekdayOf(dayKey) === 0
}

/** 0=일 … 6=토. 형식이 어긋나면 -1 — 화면이 죽지 않는다. */
function weekdayOf(dayKey: string): number {
  const p = dayKey.split('-')
  if (p.length !== 3) return -1
  const y = Number(p[0])
  const m = Number(p[1])
  const d = Number(p[2])
  if (!Number.isInteger(y) || !Number.isInteger(m) || !Number.isInteger(d)) return -1
  if (m < 1 || m > 12 || d < 1 || d > 31) return -1
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay()
}
